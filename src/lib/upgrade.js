// Network access goes through a fetcher so tests can pass a fake one.
// RN_BUDDY_DIFF_DIR=<folder> makes `rn-buddy upgrade` read everything from local files instead of the
// network (used by the CLI tests, handy for trying out a diff offline). The folder holds:
//   RELEASES               the rn-diff-purge version list, one version per line
//   <from>..<to>.diff      template diffs
//   registry.json          { packuments: { name: npm metadata }, latest: { name: package.json }, directory: {...} }
export function createFetcher({ dir = process.env.RN_BUDDY_DIFF_DIR } = {}) {
  if (dir) return localFetcher(dir);
  return {
    // Abbreviated npm metadata: every version and the dist-tags.
    packument: (name) =>
      get(`https://registry.npmjs.org/${name.replace('/', '%2F')}`, {
        json: true,
        headers: { accept: 'application/vnd.npm.install-v1+json' },
      }),
    releases: async () => parseReleases(await get(RELEASES)),
    diff: (from, to) => get(`${DIFFS}/${from}..${to}.diff`),
    latest: npmLatest,
    directory: checkPackages,
  };
}

function localFetcher(dir) {
  const read = (file) => {
    try {
      return readFileSync(path.join(dir, file), 'utf8');
    } catch {
      return null;
    }
  };
  const registry = JSON.parse(read('registry.json') ?? '{}');
  return {
    packument: async (name) => registry.packuments?.[name] ?? null,
    releases: async () => parseReleases(read('RELEASES')),
    diff: async (from, to) => read(`${from}..${to}.diff`),
    latest: async (name) => registry.latest?.[name] ?? null,
    directory: async () => registry.directory ?? {},
  };
}

async function get(url, { json = false, headers = {} } = {}) {
  try {
    const response = await fetch(url, {
      headers: { 'user-agent': 'rn-buddy', ...headers },
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });
    if (!response.ok) return null;
    return json ? await response.json() : await response.text();
  } catch {
    return null;
  }
}

function parseReleases(text) {
  return text ? text.split('\n').map((line) => line.trim()).filter((line) => semver.valid(line)) : null;
}

// The version in node_modules, or the lowest version the package.json range allows.
export function currentVersion(root, name, spec) {
  const installed = installedVersion(root, name);
  if (installed) return installed;
  try {
    return semver.minVersion(spec)?.version ?? null;
  } catch {
    return null;
  }
}

// "0.83" → the latest 0.83.x, "0.83.1" → itself, nothing → latest. `what` names the thing for errors.
export function resolveVersion(requested, packument, what = 'React Native') {
  const versions = Object.keys(packument.versions ?? {});
  const tags = packument['dist-tags'] ?? {};
  const stable = versions.filter((version) => semver.valid(version) && !semver.prerelease(version));
  const latest = tags.latest;
  if (!requested) return latest;
  if (tags[requested]) return tags[requested];

  const wanted = String(requested).replace(/^v/, '');
  if (/^\d+(\.\d+)?$/.test(wanted)) {
    const found = semver.maxSatisfying(stable, `${wanted}.x`);
    if (found) return found;
    throw new Error(`${what} ${wanted} doesn't exist (yet). The latest version is ${latest}.`);
  }
  if (versions.includes(wanted)) return wanted;
  throw new Error(`${what} ${requested} doesn't exist. Use a version like ${semver.major(latest)}.${semver.minor(latest)} or ${latest}.`);
}

// Upgrading one minor version at a time is what the React Native docs recommend: each release's
// breaking changes are listed separately. Returns { minors, next } when the jump is bigger, else null.
export function nextMinorAdvice(from, to, packument) {
  if (semver.major(from) !== semver.major(to)) return null;
  const minors = semver.minor(to) - semver.minor(from);
  if (minors <= 1) return null;
  const stable = Object.keys(packument.versions ?? {}).filter((v) => semver.valid(v) && !semver.prerelease(v));
  const next = stable
    .filter((v) => semver.major(v) === semver.major(from) && semver.minor(v) > semver.minor(from) && semver.lt(v, to))
    .sort(semver.compare);
  if (next.length === 0) return null;
  const minor = semver.minor(next[0]);
  const target = semver.maxSatisfying(next, `${semver.major(from)}.${minor}.x`);
  return { minors, next: target };
}

// rn-diff-purge has a template for most versions; use the closest one at or below `version` in the same minor.
export function templateVersion(version, releases) {
  if (releases.includes(version)) return version;
  const prerelease = Boolean(semver.prerelease(version));
  const candidates = releases.filter(
    (release) =>
      semver.major(release) === semver.major(version) &&
      semver.minor(release) === semver.minor(version) &&
      semver.lte(release, version) &&
      (prerelease || !semver.prerelease(release)),
  );
  return candidates.sort(semver.rcompare)[0] ?? null;
}

// The names the template's RnDiffApp becomes in this project.
export function projectNames(root, pkg) {
  const appJson = readJson(path.join(root, 'app.json'));
  const iosDir = iosAppDir(root);
  const project = pbxproj(root);
  const appName = appJson?.name ?? (iosDir && path.basename(iosDir)) ?? pkg.name ?? TEMPLATE_NAME;
  const iosName = iosDir ? path.basename(iosDir) : appName;
  const gradle = readText(androidAppGradle(root)) ?? '';
  const androidPackage =
    /^\s*namespace\s*=?\s*["']([\w.]+)["']/m.exec(gradle)?.[1] ??
    /^\s*applicationId\s*=?\s*["']([\w.]+)["']/m.exec(gradle)?.[1] ??
    `com.${appName.toLowerCase().replace(/[^a-z0-9]/g, '')}`;
  return {
    appName,
    iosName,
    xcodeName: project ? path.basename(path.dirname(project), '.xcodeproj') : iosName,
    androidPackage,
  };
}

// Template path → project path: RnDiffApp/ios/RnDiffApp/AppDelegate.swift → ios/DemoApp/AppDelegate.swift.
export function mapPath(file, names) {
  let mapped = file.replace(/^RnDiffApp\//, '');
  mapped = mapped.replace('com/rndiffapp/', `${names.androidPackage.replaceAll('.', '/')}/`);
  if (mapped.startsWith('ios/')) {
    return mapped.replace(`ios/${TEMPLATE_NAME}.xcodeproj`, `ios/${names.xcodeName}.xcodeproj`).replaceAll(TEMPLATE_NAME, names.iosName);
  }
  return mapped.replaceAll(TEMPLATE_NAME, names.appName);
}

// Template text → project text. In the Xcode project and Podfile, RnDiffApp is the iOS target;
// in code (AppDelegate, MainActivity) it's the registered app name from app.json.
export function mapText(text, names, file) {
  const iosConfig = file.startsWith('ios/') && !/\.(swift|mm?|h)$/.test(file);
  return text
    .replaceAll(TEMPLATE_PACKAGE, names.androidPackage)
    .replaceAll(TEMPLATE_NAME, iosConfig ? names.iosName : names.appName)
    .replaceAll('rndiffapp', names.appName.toLowerCase());
}

export function mapDiff(files, names) {
  return files.map((file) => {
    const oldPath = file.oldPath && mapPath(file.oldPath, names);
    const newPath = file.newPath && mapPath(file.newPath, names);
    const textFile = newPath ?? oldPath;
    return {
      ...file,
      oldPath,
      newPath,
      hunks: file.hunks.map((hunk) => ({
        ...hunk,
        lines: hunk.lines.map((line) => ({ ...line, text: mapText(line.text, names, textFile) })),
      })),
    };
  });
}

// Reads the template's package.json changes: { bumps: { name: { from, to, dev } }, engines: { from, to } | null }.
// `from` is null for packages the template added, `to` is null for packages it removed.
export function packageJsonChanges(fileDiff) {
  const bumps = {};
  let engines = null;
  let section = null;
  for (const line of fileDiff?.hunks.flatMap((hunk) => hunk.lines) ?? []) {
    const open = /^\s*"([^"]+)":\s*\{/.exec(line.text);
    if (open) {
      section = open[1];
      continue;
    }
    if (/^\s*\}/.test(line.text)) {
      section = null;
      continue;
    }
    const entry = /^\s*"([^"]+)":\s*"([^"]*)",?\s*$/.exec(line.text);
    if (!entry || line.type === ' ') continue;
    const [, name, version] = entry;
    const side = line.type === '-' ? 'from' : 'to';
    if (section === 'dependencies' || section === 'devDependencies') {
      bumps[name] ??= { from: null, to: null, dev: section === 'devDependencies' };
      bumps[name][side] = version;
    } else if (section === 'engines' && name === 'node') {
      engines ??= { from: null, to: null };
      engines[side] = version;
    }
  }
  return { bumps, engines };
}

// What changes in the project's package.json: [{ name, from, to, dev }], from is null for a package that gets added.
// React Native packages go to the target version; react and the template's tooling (devDependencies such as
// typescript or @react-native-community/cli) follow the template. Libraries are left to you: see checkLibraries.
export function planPackages(pkg, { bumps = {} } = {}, target) {
  const changes = [];
  const follows = (name) => name === 'react' || bumps[name]?.dev;
  for (const [field, dev] of [['dependencies', false], ['devDependencies', true]]) {
    for (const [name, spec] of Object.entries(pkg[field] ?? {})) {
      const want = LOCKSTEP(name) ? target : follows(name) ? bumps[name]?.to : null;
      if (!want || spec === want || isNewer(spec, want)) continue;
      changes.push({ name, from: spec, to: want, dev });
    }
  }
  const has = (name) => Boolean(pkg.dependencies?.[name] ?? pkg.devDependencies?.[name]);
  for (const [name, bump] of Object.entries(bumps)) {
    // New React Native tooling (e.g. @react-native/jest-preset): the template's config files need it.
    if (bump.from === null && bump.to && name.startsWith('@react-native/') && !TEMPLATE_ONLY.has(name) && !has(name)) {
      changes.push({ name, from: null, to: LOCKSTEP(name) ? target : bump.to, dev: bump.dev });
    }
  }
  return changes;
}

// Template packages that were removed: you may not need them anymore, but rn-buddy doesn't remove them.
export function removedPackages(pkg, { bumps = {} } = {}) {
  return Object.entries(bumps)
    .filter(([name, bump]) => bump.from && bump.to === null && (pkg.dependencies?.[name] ?? pkg.devDependencies?.[name]))
    .map(([name]) => name);
}

// Whether the project's range already starts at or above the template's version.
function isNewer(spec, want) {
  try {
    const have = semver.minVersion(spec);
    const next = semver.minVersion(want);
    return Boolean(have && next && semver.gte(have, next));
  } catch {
    return true; // git URLs, workspace:, ...: not ours to touch
  }
}

export function updatePackageJson(text, changes, engines) {
  const indent = /^(\s+)"/m.exec(text)?.[1] ?? '  ';
  const json = JSON.parse(text);
  for (const { name, to, dev } of changes) {
    let field = dev ? 'devDependencies' : 'dependencies';
    if (json.dependencies?.[name] !== undefined) field = 'dependencies';
    else if (json.devDependencies?.[name] !== undefined) field = 'devDependencies';
    json[field] ??= {};
    json[field][name] = to;
  }
  if (engines?.to && engines.from && json.engines?.node === engines.from) json.engines.node = engines.to;
  return JSON.stringify(json, null, indent) + (text.endsWith('\n') ? '\n' : '');
}

// What to do with each file of the template diff (package.json is handled separately):
// { file, action: 'create' | 'modify' | 'delete' | 'rename', status: 'apply' | 'done' | 'manual' | 'skip',
//   note, reason?, content?, from?, mode?, hunks }
export function planFiles(root, files, { to } = {}) {
  return files.map((diff) => planFile(root, diff, to)).filter(Boolean);
}

function planFile(root, diff, to) {
  const file = diff.status === 'deleted' ? diff.oldPath : diff.newPath;
  if (!file || file === 'package.json' || IGNORED.has(file)) return null;
  const action = { added: 'create', deleted: 'delete', renamed: 'rename', modified: 'modify' }[diff.status];
  const base = { file, action, note: describeChange(file, diff), hunks: diff.hunks };

  const platform = file.split('/')[0];
  if ((platform === 'android' || platform === 'ios') && !existsSync(path.join(root, platform))) {
    return { ...base, status: 'skip', reason: `no ${platform}/ folder` };
  }

  if (diff.binary) {
    if (file.endsWith('gradle-wrapper.jar')) {
      const gradle = gradleVersions(diff.gradle);
      const command = `cd android && ./gradlew wrapper --gradle-version ${gradle?.to ?? '<new version>'}`;
      return { ...base, status: 'manual', reason: `replace it with \`${command}\``, command };
    }
    return { ...base, status: 'manual', reason: `binary file: copy it from ${TEMPLATE_TREE}/${to}/RnDiffApp/` };
  }

  if (diff.status === 'added') {
    const content = addedContent(diff);
    const current = readText(path.join(root, file));
    if (current === null) return { ...base, status: 'apply', content, mode: diff.mode };
    if (sameText(current, content)) return { ...base, status: 'done' };
    return { ...base, status: 'manual', reason: 'already exists with other content: compare it with the change below' };
  }

  if (diff.status === 'deleted') {
    const current = readText(path.join(root, file));
    if (current === null) return { ...base, status: 'done' };
    if (sameText(current, removedContent(diff))) return { ...base, status: 'apply' };
    return { ...base, status: 'manual', reason: 'removed from the template, but you changed it: delete it if you no longer need it' };
  }

  const from = diff.status === 'renamed' ? diff.oldPath : file;
  const target = findProjectFile(root, from);
  if (!target) {
    if (diff.status === 'renamed' && existsSync(path.join(root, file))) return { ...base, status: 'done' };
    if (platform === 'android' || platform === 'ios') return { ...base, status: 'manual', reason: 'not found in your project' };
    return { ...base, status: 'skip', reason: 'not in your project' };
  }
  const relative = path.relative(root, target);
  const current = readFileSync(target, 'utf8');
  const result = applyHunks(current, diff.hunks);
  if (result.failed.length > 0) {
    if (APP_CODE.has(file)) return { ...base, status: 'skip', reason: "your own code (the template's sample screen changed)" };
    return { ...base, file: relative, status: 'manual', reason: 'you changed this file: do by hand', failed: result.failed };
  }
  if (diff.status === 'renamed') return { ...base, status: 'apply', from: relative, content: result.content };
  if (result.applied === 0) return { ...base, file: relative, status: 'done' };
  return { ...base, file: relative, status: 'apply', content: result.content };
}

// MainApplication/MainActivity may live in another folder (or be Java): find them by name.
function findProjectFile(root, file) {
  const direct = path.join(root, file);
  if (existsSync(direct)) return direct;
  const name = path.basename(file);
  if (/^MainApplication\.(kt|java)$/.test(name)) return mainApplication(root);
  if (/^MainActivity\.(kt|java)$/.test(name)) return mainActivity(root);
  return null;
}

function sameText(a, b) {
  const clean = (text) => text.replace(/\r\n/g, '\n').replace(/\n+$/, '');
  return clean(a) === clean(b);
}

// A short explanation of what a template file change is about.
export function describeChange(file, diff) {
  const name = path.basename(file);
  const changed = (pattern) => {
    const values = { from: null, to: null };
    for (const line of diff.hunks.flatMap((hunk) => hunk.lines)) {
      const match = pattern.exec(line.text);
      if (match && line.type === '-') values.from = match[1];
      if (match && line.type === '+') values.to = match[1];
    }
    return values.from && values.to && values.from !== values.to ? values : null;
  };

  if (name === 'gradle-wrapper.properties') {
    const gradle = gradleVersions(diff);
    return gradle ? `Gradle ${gradle.from} → ${gradle.to}` : 'Gradle version';
  }
  if (name === 'gradle-wrapper.jar') return 'Gradle wrapper (binary file)';
  if (file === 'android/build.gradle' || file === 'android/build.gradle.kts') {
    const keys = {
      compileSdkVersion: 'compileSdk',
      targetSdkVersion: 'targetSdk',
      minSdkVersion: 'minSdk',
      buildToolsVersion: 'build tools',
      ndkVersion: 'NDK',
      kotlinVersion: 'Kotlin',
    };
    const parts = Object.entries(keys)
      .map(([key, label]) => [label, changed(new RegExp(`${key}\\s*=\\s*"?([\\w.-]+)"?`))])
      .filter(([, values]) => values)
      .map(([label, values]) => `${label} ${values.from} → ${values.to}`);
    return parts.length > 0 ? parts.join(', ') : 'Android build settings';
  }
  if (name === 'Podfile') {
    const ios = changed(/platform :ios,\s*'?([\w.]+)'?/);
    return ios ? `minimum iOS ${ios.from} → ${ios.to}` : 'CocoaPods setup';
  }
  if (diff.status === 'added' && name === 'SceneDelegate.swift') return 'new: iOS window and scene setup';
  const notes = {
    'MainApplication.kt': 'Android app startup code',
    'MainApplication.java': 'Android app startup code',
    'MainActivity.kt': 'Android main screen code',
    'MainActivity.java': 'Android main screen code',
    'AppDelegate.swift': 'iOS app startup code',
    'AppDelegate.mm': 'iOS app startup code',
    'project.pbxproj': 'Xcode project settings',
    'Info.plist': 'iOS app settings',
    'AndroidManifest.xml': 'Android app settings',
    'gradle.properties': 'Gradle settings',
    'settings.gradle': 'Gradle project list',
    'build.gradle': 'Android app build settings',
    gradlew: 'Gradle wrapper script',
    'gradlew.bat': 'Gradle wrapper script (Windows)',
    Gemfile: 'Ruby gems for CocoaPods',
    'metro.config.js': 'Metro bundler config',
    'babel.config.js': 'Babel config',
    'jest.config.js': 'Jest config',
    'tsconfig.json': 'TypeScript config',
    '.eslintrc.js': 'ESLint config',
    '.prettierrc.js': 'Prettier config',
    '.watchmanconfig': 'Watchman config',
    'App.tsx': 'sample screen',
  };
  const note = notes[name] ?? '';
  if (diff.status === 'added') return note ? `new: ${note}` : 'new in the template';
  if (diff.status === 'deleted') return 'no longer in the template';
  return note;
}

function gradleVersions(diff) {
  if (!diff) return null;
  const values = { from: null, to: null };
  for (const line of diff.hunks.flatMap((hunk) => hunk.lines)) {
    const match = /gradle-([\d.]+(?:-[\w.]+)?)-(?:bin|all)\.zip/.exec(line.text);
    if (match && line.type === '-') values.from = match[1];
    if (match && line.type === '+') values.to = match[1];
  }
  return values.to ? values : null;
}

// Which native libraries support the target version. One row per library:
// { name, status: 'ok' | 'warn', message, version?, hint? } (the shape ui.printRows prints).
export async function checkLibraries(project, target, fetcher) {
  const { root, pkg } = project;
  const names = Object.keys(pkg.dependencies ?? {}).filter(
    (name) => !LOCKSTEP(name) && name !== 'react' && !name.startsWith('@react-native-community/cli') && name !== 'expo',
  );
  if (names.length === 0) return [];
  const directory = (await fetcher.directory(names)) ?? {};
  const libraries = names.filter((name) => hasNativeCode(root, name) === true || directory[name]).sort();
  const manifests = await Promise.all(libraries.map((name) => fetcher.latest(name)));
  return libraries.map((name, i) => libraryRow(name, manifests[i], directory[name], target, pkg.dependencies[name]));
}

export function libraryRow(name, manifest, info, target, spec) {
  const minor = `${semver.major(target)}.${semver.minor(target)}`;
  if (!manifest) return { name, status: 'warn', message: "couldn't check: not found on npm" };
  const range = manifest.peerDependencies?.['react-native'];
  const hint = updateHint(spec, manifest.version);
  const extra = [];
  if (info?.unmaintained) extra.push('marked unmaintained on React Native Directory: look for an alternative');
  if (info?.newArchitecture === 'unsupported') extra.push("it doesn't support the New Architecture");

  let row;
  if (!range) {
    const message = `unknown: ${manifest.version} doesn't say which React Native versions it supports`;
    row = { name, status: 'warn', message, hint: 'check its changelog' };
  } else if (range.trim() === '*') {
    row = { name, status: 'ok', message: `${manifest.version} allows any React Native version`, hint };
  } else if (semver.satisfies(target, range, { includePrerelease: true })) {
    row = { name, status: 'ok', message: `${manifest.version} supports ${minor}`, hint };
  } else {
    row = { name, status: 'warn', message: `no version supports ${minor} yet (${manifest.version} needs react-native ${range})` };
  }
  if (extra.length > 0) row = { ...row, status: 'warn', hint: [...extra, row.hint].filter(Boolean).join('; ') };
  return row;
}

function updateHint(spec, latest) {
  try {
    return spec && !semver.satisfies(latest, spec) ? `update it to ${latest} too` : undefined;
  } catch {
    return undefined;
  }
}

export function upgradeHelperUrl(from, to) {
  return `https://react-native-community.github.io/upgrade-helper/?from=${from}&to=${to}`;
}

// Works out the whole upgrade before anything changes. Throws a friendly Error for usage
// problems (downgrade, unknown version, offline).
export async function planUpgrade(project, requested, { fetcher = createFetcher() } = {}) {
  const { root, pkg } = project;
  const spec = pkg.dependencies?.['react-native'];
  if (!spec) throw new Error("react-native isn't in this project's dependencies, so there is nothing to upgrade.");
  const from = currentVersion(root, 'react-native', spec);
  if (!from) throw new Error(`Can't tell which React Native version "${spec}" is. Install your packages first.`);

  const packument = await fetcher.packument('react-native');
  if (!packument) throw new Error(OFFLINE);
  const to = resolveVersion(requested, packument);
  if (semver.lt(to, from)) {
    throw new Error(`This project has React Native ${from}, which is newer than ${to}. rn-buddy upgrade doesn't downgrade.`);
  }
  const manager = packageManager(root, pkg);
  if (semver.eq(to, from)) return { kind: 'react-native', from, to, upToDate: true, manager };

  const releases = await fetcher.releases();
  if (!releases) throw new Error(OFFLINE);
  const fromTemplate = templateVersion(from, releases);
  const toTemplate = templateVersion(to, releases);

  let files = [];
  let packageJson = { bumps: {}, engines: null };
  let diffMissing = false;
  if (fromTemplate && toTemplate && fromTemplate !== toTemplate) {
    const text = await fetcher.diff(fromTemplate, toTemplate);
    if (text === null) diffMissing = true;
    else {
      const diff = mapDiff(parseDiff(text), projectNames(root, pkg));
      // The jar's manual step needs the Gradle version from the properties file.
      const properties = diff.find((file) => file.newPath?.endsWith('gradle-wrapper.properties'));
      for (const file of diff) if (file.binary) file.gradle = properties;
      packageJson = packageJsonChanges(diff.find((file) => file.newPath === 'package.json'));
      files = planFiles(root, diff, { to: toTemplate });
    }
  } else if (!fromTemplate || !toTemplate) {
    diffMissing = true;
  }

  return {
    kind: 'react-native',
    from,
    to,
    fromTemplate,
    toTemplate,
    manager,
    advice: nextMinorAdvice(from, to, packument),
    packages: planPackages(pkg, packageJson, to),
    removed: removedPackages(pkg, packageJson),
    // engines.node only follows the template when you never changed it.
    engines: packageJson.engines?.to && pkg.engines?.node === packageJson.engines.from ? packageJson.engines : null,
    files,
    diffMissing,
    libraries: await checkLibraries(project, to, fetcher),
    helper: upgradeHelperUrl(fromTemplate ?? from, toTemplate ?? to),
  };
}

export function installCommand(manager) {
  return { command: manager, args: ['install'] };
}

// Writes the files and package.json, then installs packages and pods.
// `run(command, args, cwd)` returns true on success; tests pass a fake one.
// Returns { written: [file], installOk, pods, podsOk }.
export function applyUpgrade({ root }, plan, { run = runCommand, platform = process.platform } = {}) {
  const written = [];
  // Paths come from a downloaded diff: never touch anything outside the project.
  const inside = (file) => {
    const relative = path.relative(root, path.resolve(root, file));
    return relative !== '' && !relative.startsWith('..') && !path.isAbsolute(relative);
  };
  for (const item of plan.files.filter((file) => file.status === 'apply')) {
    if (!inside(item.file) || (item.from && !inside(item.from))) continue;
    const target = path.join(root, item.file);
    if (item.action === 'delete') {
      rmSync(target, { force: true });
    } else {
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, item.content);
      if (item.mode === '100755') chmodSync(target, 0o755);
      if (item.action === 'rename') rmSync(path.join(root, item.from), { force: true });
    }
    written.push(item.file);
  }

  if (plan.packages.length > 0 || plan.engines) {
    const file = path.join(root, 'package.json');
    writeFileSync(file, updatePackageJson(readFileSync(file, 'utf8'), plan.packages, plan.engines));
    written.push('package.json');
  }

  const install = installCommand(plan.manager);
  const installOk = run(install.command, install.args, root);
  if (!installOk) return { written, installOk, pods: null, podsOk: null };

  const pods = podCommand(root, platform);
  let podsOk = null;
  if (pods) {
    const gems = pods.command !== 'bundle' || run('bundle', ['check'], root, { quiet: true }) || run('bundle', ['install'], root);
    podsOk = gems && run(pods.command, pods.args, pods.cwd);
  }
  return { written, installOk, pods, podsOk };
}

// Expo projects upgrade the SDK with `npx expo install`, which also picks the matching
// react-native and library versions. One SDK at a time, like React Native minors.
export async function planExpo(project, requested, { fetcher = createFetcher() } = {}) {
  const { root, pkg } = project;
  const spec = pkg.dependencies?.expo ?? pkg.devDependencies?.expo;
  const from = currentVersion(root, 'expo', spec);
  const packument = await fetcher.packument('expo');
  if (!packument) throw new Error(OFFLINE);
  const to = resolveVersion(requested, packument, 'Expo SDK');
  if (from && semver.lt(to, from)) {
    throw new Error(`This project has Expo ${from}, which is newer than ${to}. rn-buddy upgrade doesn't downgrade.`);
  }
  const base = { kind: 'expo', from, to, fromSdk: from && semver.major(from), toSdk: semver.major(to) };
  if (from && semver.eq(to, from)) return { ...base, upToDate: true };

  // A full version is installed as is; otherwise the SDK's newest patch, the way the Expo docs write it.
  const exact = requested && /^v?\d+\.\d+\.\d+/.test(String(requested));
  const expoSpec = exact ? to : `^${semver.major(to)}.0.0`;
  const skipped = from ? semver.major(to) - semver.major(from) : 0;
  const nextSdk = skipped > 1 ? semver.major(from) + 1 : null;
  return {
    ...base,
    advice: nextSdk ? { sdks: skipped, next: nextSdk } : null,
    commands: [
      { command: 'npx', args: ['expo', 'install', `expo@${expoSpec}`, '--fix'] },
      { command: 'npx', args: ['expo', 'install', '--fix'] },
      { command: 'npx', args: ['expo-doctor'], optional: true },
    ],
    prebuild: ['android', 'ios'].filter((dir) => existsSync(path.join(root, dir))),
    changelog: EXPO_CHANGELOG,
  };
}

// Runs the Expo commands in order and stops at the first failure.
// Returns { done: [command], failed: command | null }; expo-doctor findings don't count as a failure.
export function applyExpo({ root }, plan, { run = runCommand } = {}) {
  const done = [];
  for (const step of plan.commands) {
    const success = run(step.command, step.args, root);
    if (!success && !step.optional) return { done, failed: step };
    done.push(step);
  }
  return { done, failed: null };
}

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

function runCommand(command, args, cwd, { quiet = false } = {}) {
  const result = spawnSync(command, args, { cwd, stdio: quiet ? 'ignore' : 'inherit', shell: process.platform === 'win32' });
  return result.status === 0;
}
